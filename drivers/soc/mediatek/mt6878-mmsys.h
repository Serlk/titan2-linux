#ifndef __SOC_MEDIATEK_MT6878_MMSYS_H
#define __SOC_MEDIATEK_MT6878_MMSYS_H

/*
 * MT6878 routes the display engines through crossbars: each source has a
 * "multiple output" enable register with one bit per destination, which
 * the MediaTek downstream driver only ever sets (read-modify-write OR). The routes below
 * write the whole destination field instead, so that the connections left
 * by the boot loader (OVL0_2L cascaded into OVL1_2L/OVL2_2L, then the full
 * PQ chain) are dropped when OVL0_2L is wired straight to DSI0.
 */
#define MT6878_DISPSYS_BYPASS_MUX_SHADOW	0xc00
#define MT6878_BYPASS_MUX_SHADOW			BIT(0)

#define MT6878_MMSYS_OVL_CON			0xc08
#define MT6878_OVL_CON_MAIN_MASK			GENMASK(7, 0)
#define MT6878_OVL0_2L_TO_BLEND_CROSSBAR0		BIT(2)

#define MT6878_MMSYS_CROSSBAR_CON		0xc0c
#define MT6878_CROSSBAR_CON_MASK			GENMASK(23, 16)

#define MT6878_OVL_BG_CROSSBAR0_MOUT_EN		0xc10
#define MT6878_OVL_BG_CROSSBAR1_MOUT_EN		0xc14
#define MT6878_OVL_BG_CROSSBAR_TO_OVL1_2L		BIT(1)
#define MT6878_OVL_BG_CROSSBAR_TO_OVL2_2L		BIT(2)

#define MT6878_OVL_BLEND_CROSSBAR0_MOUT_EN	0xc34
#define MT6878_OVL_BLEND_CROSSBAR2_MOUT_EN	0xc3c
#define MT6878_OVL_BLEND_CROSSBAR_TO_PQ0_IN_CB0		BIT(0)

#define MT6878_PQ_IN_CROSSBAR0_MOUT_EN		0xd00
#define MT6878_PQ_IN_CROSSBAR_MASK			GENMASK(4, 0)
#define MT6878_PQ0_IN_CB_TO_PQ_OUT_CB4			BIT(2)

#define MT6878_PQ_OUT_CROSSBAR0_MOUT_EN		0xd20
#define MT6878_PQ_OUT_CROSSBAR4_MOUT_EN		0xd30
#define MT6878_PQ_OUT_CROSSBAR_MASK			GENMASK(3, 0)
#define MT6878_PQ_OUT_CB_TO_SPLIT_OUT_CB2		BIT(1)

#define MT6878_SPLIT_OUT_CROSSBAR2_MOUT_EN	0xd54
#define MT6878_SPLIT_OUT_CROSSBAR_MASK			GENMASK(4, 0)
#define MT6878_SPLIT_OUT_CB_TO_COMP0_OUT_CB2		BIT(2)

#define MT6878_COMP_OUT_CROSSBAR2_MOUT_EN	0xd7c
#define MT6878_COMP_OUT_CROSSBAR_MASK			GENMASK(2, 0)
#define MT6878_COMP_OUT_CB_TO_DSI0			BIT(0)

/*
 * OVL0_2L -> DSI0 with the picture quality engines bypassed:
 * OVL0_2L -> blend crossbar 0 -> PQ in crossbar 0 -> PQ out crossbar 4 ->
 * split out crossbar 2 -> comp out crossbar 2 -> DSI0.
 */
static const struct mtk_mmsys_routes mmsys_mt6878_routing_table[] = {
	MMSYS_ROUTE(OVL_2L0, DSI0,
		    MT6878_DISPSYS_BYPASS_MUX_SHADOW, MT6878_BYPASS_MUX_SHADOW,
		    MT6878_BYPASS_MUX_SHADOW),
	MMSYS_ROUTE(OVL_2L0, DSI0,
		    MT6878_MMSYS_CROSSBAR_CON, MT6878_CROSSBAR_CON_MASK,
		    MT6878_CROSSBAR_CON_MASK),
	MMSYS_ROUTE(OVL_2L0, DSI0,
		    MT6878_MMSYS_OVL_CON, MT6878_OVL_CON_MAIN_MASK,
		    MT6878_OVL0_2L_TO_BLEND_CROSSBAR0),
	MMSYS_ROUTE(OVL_2L0, DSI0,
		    MT6878_OVL_BG_CROSSBAR0_MOUT_EN, MT6878_OVL_BG_CROSSBAR_TO_OVL1_2L,
		    0),
	MMSYS_ROUTE(OVL_2L0, DSI0,
		    MT6878_OVL_BG_CROSSBAR1_MOUT_EN, MT6878_OVL_BG_CROSSBAR_TO_OVL2_2L,
		    0),
	MMSYS_ROUTE(OVL_2L0, DSI0,
		    MT6878_OVL_BLEND_CROSSBAR0_MOUT_EN,
		    MT6878_OVL_BLEND_CROSSBAR_TO_PQ0_IN_CB0,
		    MT6878_OVL_BLEND_CROSSBAR_TO_PQ0_IN_CB0),
	MMSYS_ROUTE(OVL_2L0, DSI0,
		    MT6878_OVL_BLEND_CROSSBAR2_MOUT_EN,
		    MT6878_OVL_BLEND_CROSSBAR_TO_PQ0_IN_CB0, 0),
	MMSYS_ROUTE(OVL_2L0, DSI0,
		    MT6878_PQ_IN_CROSSBAR0_MOUT_EN, MT6878_PQ_IN_CROSSBAR_MASK,
		    MT6878_PQ0_IN_CB_TO_PQ_OUT_CB4),
	MMSYS_ROUTE(OVL_2L0, DSI0,
		    MT6878_PQ_OUT_CROSSBAR0_MOUT_EN, MT6878_PQ_OUT_CROSSBAR_MASK,
		    0),
	MMSYS_ROUTE(OVL_2L0, DSI0,
		    MT6878_PQ_OUT_CROSSBAR4_MOUT_EN, MT6878_PQ_OUT_CROSSBAR_MASK,
		    MT6878_PQ_OUT_CB_TO_SPLIT_OUT_CB2),
	MMSYS_ROUTE(OVL_2L0, DSI0,
		    MT6878_SPLIT_OUT_CROSSBAR2_MOUT_EN, MT6878_SPLIT_OUT_CROSSBAR_MASK,
		    MT6878_SPLIT_OUT_CB_TO_COMP0_OUT_CB2),
	MMSYS_ROUTE(OVL_2L0, DSI0,
		    MT6878_COMP_OUT_CROSSBAR2_MOUT_EN, MT6878_COMP_OUT_CROSSBAR_MASK,
		    MT6878_COMP_OUT_CB_TO_DSI0),
};

#endif /* __SOC_MEDIATEK_MT6878_MMSYS_H */
